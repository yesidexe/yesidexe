#!/usr/bin/env python3
"""Generate img/header.svg and the README header block from header.txt."""

from __future__ import annotations

import html
import re
from pathlib import Path
from urllib.parse import quote_plus
from urllib.request import Request, urlopen

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "header.txt"
TARGET = ROOT / "img" / "header.svg"
README = ROOT / "README.md"

START = "<!-- HEADER:START -->"
END = "<!-- HEADER:END -->"

BASE_URL = (
    "https://readme-typing-svg.demolab.com"
    "?font=JetBrains+Mono"
    "&weight=600"
    "&size=24"
    "&duration=3000"
    "&pause=1000"
    "&color=58A6FF"
    "&center=true"
    "&vCenter=true"
    "&repeat=true"
    "&width=650"
    "&height=55"
)


def read_lines() -> list[str]:
    lines = [
        line.strip()
        for line in SOURCE.read_text(encoding="utf-8").splitlines()
        if line.strip() and not line.lstrip().startswith("#")
    ]
    if not lines:
        raise SystemExit("header.txt has no lines.")
    if len(lines) > 3:
        raise SystemExit("header.txt supports up to 3 lines.")
    return lines


def build_url(lines: list[str]) -> str:
    encoded = ";".join(quote_plus(line) for line in lines)
    return f"{BASE_URL}&lines={encoded}"


def update_readme(lines: list[str]) -> None:
    block = (
        f"{START}\n"
        f'  <a href="https://git.io/typing-svg">\n'
        f'    <img src="img/header.svg" alt="{html.escape(lines[0], quote=True)}" />\n'
        f"  </a>\n"
        f"  {END}"
    )
    text = README.read_text(encoding="utf-8")
    new_text, count = re.subn(
        rf"{re.escape(START)}.*?{re.escape(END)}",
        lambda _: block,
        text,
        count=1,
        flags=re.DOTALL,
    )
    if count != 1:
        raise SystemExit(f"Could not find {START} ... {END} in README.md.")
    README.write_text(new_text, encoding="utf-8")


def main() -> None:
    lines = read_lines()
    url = build_url(lines)
    request = Request(url, headers={"User-Agent": "Mozilla/5.0"})
    try:
        with urlopen(request, timeout=30) as response:
            svg = response.read()
    except Exception as exc:
        raise SystemExit(f"Could not fetch the header SVG: {exc}") from exc
    if b"<svg" not in svg:
        raise SystemExit("The typing SVG service returned an unexpected response.")
    svg = (
        b"<!-- Generated by scripts/update_header.py from header.txt. "
        b"Do not edit manually. -->\n" + svg
    )
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_bytes(svg)
    update_readme(lines)
    print(f"Updated {TARGET.relative_to(ROOT)} and README.md.")


if __name__ == "__main__":
    main()
